#!/usr/bin/env bash
# scripts/mashup.sh - one long replay that chains every timing knob, with a
# multiplier per knob so the whole thing can be sped up or slowed down without
# retuning the numbers in the script.
#
# This is a generator, not a replay script: run it directly. It emits the scaled
# sequence and pipes it into cmd-replay.sh, so `cmd-replay.sh scripts/mashup.sh`
# is the wrong way round and is rejected.
#
#   ./scripts/mashup.sh                       # base speeds
#   ./scripts/mashup.sh -s 2 -d .5 -P .5      # sleeps x2, delays/pauses x0.5
#   ./scripts/mashup.sh -n                    # print the scaled script, don't run
#   ./scripts/mashup.sh -w 40 -C              # extra flags go to cmd-replay.sh
#
# The multipliers scale the script's own directives only:
#   -s  every @sleep (hold the previous screen)
#   -d  every @delay (hold on the command line, before its output)
#   -P  the gap after each command: the -p these values feed, plus @pause
# Any -p/--pace you pass yourself wins, and -P is then ignored.
#
# Requires awk (already needed by cmd-replay.sh --pace).

set -uo pipefail

s_sleep=1
s_delay=1
s_pause=1
base_pause=1      # the unscaled -p gap after a command
print_only=0
args=()

usage() {
    cat <<'EOF'
scripts/mashup.sh - chained cmd-replay demo with per-knob multipliers

usage: scripts/mashup.sh [scale options] [-h] [cmd-replay options]

scale options:
  -s, --sleep-scale M   multiply every @sleep by M        (default 1)
  -d, --delay-scale M   multiply every @delay by M        (default 1)
  -P, --pause-scale M   multiply @pause and the base -p    (default 1)
  -b, --base-pause SEC  unscaled -p gap between steps      (default 1)
  -n, --print           print the scaled script instead of replaying it

anything else is handed to cmd-replay.sh (-C, -w, -e, -p, --pace, ...)

examples:
  ./scripts/mashup.sh
  ./scripts/mashup.sh -n -s 3 | less
  ./scripts/mashup.sh -w 40 -C --pace 3
EOF
}

is_num() { awk -v x="$1" 'BEGIN { exit !(x ~ /^([0-9]+([.][0-9]*)?|[.][0-9]+)$/) }'; }
mul() { awk -v x="$1" -v m="$2" 'BEGIN { printf "%.2f", x * m }'; }

die() { printf 'mashup.sh: %s\n' "$*" >&2; exit 2; }

while (($#)); do
    case $1 in
        -s|--sleep-scale)
            [ $# -ge 2 ] && is_num "$2" || die "$1 needs a number"
            s_sleep=$2; shift 2
            ;;
        -d|--delay-scale)
            [ $# -ge 2 ] && is_num "$2" || die "$1 needs a number"
            s_delay=$2; shift 2
            ;;
        -P|--pause-scale)
            [ $# -ge 2 ] && is_num "$2" || die "$1 needs a number"
            s_pause=$2; shift 2
            ;;
        -b|--base-pause)
            [ $# -ge 2 ] && is_num "$2" || die "$1 needs a number"
            base_pause=$2; shift 2
            ;;
        -h|--help) usage; exit 0 ;;
        -n|--print) print_only=1; shift ;;
        *) args+=("$1"); shift ;;
    esac
done

# don't fight a pause the caller chose themselves
inject_pause=1
for a in ${args[@]+"${args[@]}"}; do
    case $a in -p|--pause|--pace) inject_pause=0 ;; esac
done
if ((inject_pause)); then
    args=(-p "$(mul "$base_pause" "$s_pause")" ${args[@]+"${args[@]}"})
fi

printf 'mashup: sleep x%s, delay x%s, pause x%s\n' "$s_sleep" "$s_delay" "$s_pause" >&2
printf 'mashup: cmd-replay.sh %s -\n' "${args[*]}" >&2

{
    cat <<EOF
# generated by scripts/mashup.sh -- sleep x$s_sleep, delay x$s_delay, pause x$s_pause

# 1. no directive: the only gap after this screen is the base -p
pwd

# 2. @sleep: the previous screen lingers, then the clear, then this runs
@sleep $(mul 1 "$s_sleep")
ls -1

# 3. @delay: this line is printed, then the hold, then the output lands
@delay $(mul 1.2 "$s_delay")
git status --short

# 4. both: @sleep holds the old screen, @delay holds the command line, so the
#    two waits sit on either side of the clear and add up
@sleep $(mul 0.8 "$s_sleep")
@delay $(mul 1.5 "$s_delay")
git log --oneline -3

# 5. a short @delay next to step 3/4: same command style, snappier output
@delay $(mul 0.3 "$s_delay")
wc -l cmd-replay.sh README.md

# 6. @pause overrides the base -p for the gap after this command only
@delay $(mul 0.6 "$s_delay")
ls -1 lib
@pause $(mul 3 "$s_pause")

# 7. the end: a @pause here would do nothing (the last command has no gap after
#    it), so a trailing @sleep is what holds the final screen
ls -1 scripts
@sleep $(mul 2 "$s_sleep")
EOF
} | if ((print_only)); then cat; else ./cmd-replay.sh "${args[@]}" -; fi
